CREATE TABLE IF NOT EXISTS jobs(
  id TEXT PRIMARY KEY,
  ownerId INTEGER NOT NULL REFERENCES users(id),
  contentItemId INTEGER REFERENCES content_items(id) ON DELETE CASCADE,
  sceneId INTEGER REFERENCES scenes(id) ON DELETE SET NULL,
  type TEXT NOT NULL, -- 'FULL_VIDEO_RENDER', 'SCENE_ANIMATION', 'CHARACTER_GENERATION', 'FACE_ANIMATION'
  status TEXT NOT NULL DEFAULT 'QUEUED', -- 'QUEUED', 'INITIALIZING', 'GENERATING_CHARACTER', 'ANIMATING_FACE', 'GENERATING_MOTION', 'SYNTHESIZING_VOICE', 'RENDERING_MASTER', 'QUALITY_CHECK', 'COMPLETED', 'FAILED', 'CANCELLED'
  progress INTEGER NOT NULL DEFAULT 0, -- 0 to 100
  currentStage TEXT,
  error TEXT,
  inputPayload TEXT DEFAULT '{}',
  resultPayload TEXT DEFAULT '{}',
  createdAt TEXT DEFAULT CURRENT_TIMESTAMP,
  updatedAt TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_jobs_owner ON jobs(ownerId);
CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
